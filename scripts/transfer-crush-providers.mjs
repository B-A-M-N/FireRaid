/**
 * Transfer crush-config LLM providers into the harness attack-plane pool.
 *
 * SAFETY CONTRACT:
 *   - Reads ~/.config/crush/crush.json AND its backups (.bak/.bak2 — older
 *     key generations live there; the sweep that found the live keys mined
 *     all three) directly. Key VALUES are never printed to stdout — output
 *     shows ids, hosts, and key fingerprints only.
 *   - Writes ONLY the gitignored harness/.llm-pool.json (0600).
 *   - Live probe per provider: a 1-token chat completion against the
 *     provider's OWN first listed model. Classification:
 *       200                  → alive
 *       400/404              → auth-ok-shape  (key valid, request/model id off)
 *       429                  → auth-ok-rate   (key valid, throttled)
 *       401/402/403          → dead
 *     transport errors / timeouts → transport-error
 *
 * Usage:
 *   node scripts/transfer-crush-providers.mjs [--probe]
 *     default: extract + write pool (no network)
 *     --probe: also smoke-test each provider live (recommended)
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { homedir } from "node:os";

const CRUSH_DIR = join(homedir(), ".config", "crush");
const SOURCES = [
  { file: "crush.json", tag: "" },
  { file: "crush.json.bak", tag: "@bak" },
  { file: "crush.json.bak2", tag: "@bak2" },
];
const POOL_PATH = "harness/.llm-pool.json";

// Providers we deliberately skip: loopback dev endpoints (not a real pool
// member) and the env-indirect entry (OPENROUTER_API_KEY already wired as
// the harness .env primary — importing it here would duplicate it).
const SKIP_IDS = new Set(["logflare", "openrouter-fusion", "openrouter"]);

function fingerprint(k) {
  return `${k.slice(0, 3)}…${k.slice(-2)}(len=${k.length})`;
}
function isPlaceholder(s) {
  return typeof s !== "string" || s.startsWith("$");
}

/** Extract provider entries from one crush file. */
function extractFrom(fileName, tag) {
  const path = join(CRUSH_DIR, fileName);
  if (!existsSync(path)) return [];
  let data;
  try {
    data = JSON.parse(readFileSync(path, "utf-8"));
  } catch {
    console.log(`  skip ${fileName}: unreadable JSON`);
    return [];
  }
  const out = [];
  for (const [id, p] of Object.entries(data.providers ?? {})) {
    if (SKIP_IDS.has(id)) continue;
    const key = p?.api_key;
    const base = p?.base_url;
    if (isPlaceholder(key) || key.length < 8) continue;
    if (typeof base !== "string" || !base.startsWith("http")) continue;
    out.push({
      id: `${id}${tag}`,
      baseUrl: base.replace(/\/+$/, ""),
      apiKey: key,
      models: (p.models ?? []).map((m) => m?.id).filter((x) => typeof x === "string" && x.length > 0),
    });
  }
  return out;
}

// Extract from every source; dedup EXACT (baseUrl, apiKey) pairs so a key
// present in both main and a backup is stored once under the main id.
const extracted = [];
const seenPair = new Set();
for (const { file, tag } of SOURCES) {
  for (const e of extractFrom(file, tag)) {
    const dupKey = `${e.baseUrl}|${e.apiKey}`;
    if (seenPair.has(dupKey)) continue;
    seenPair.add(dupKey);
    extracted.push(e);
  }
}

console.log(`Extracted ${extracted.length} distinct providers from crush config (main + backups):`);
for (const e of extracted) {
  console.log(`  ${e.id.padEnd(20)} ${e.baseUrl.replace(/^https?:\/\//, "").padEnd(44)} key=${fingerprint(e.apiKey)} models=${e.models.length}`);
}

// Load prior pool (preserve probe state for unchanged entries).
let pool = {
  _comment:
    "Attack-plane LLM provider pool. Gitignored; 0600. Generated by scripts/transfer-crush-providers.mjs from the crush config (main + backups) — DO NOT COMMIT.",
  providers: {},
};
if (existsSync(POOL_PATH)) {
  try {
    pool = JSON.parse(readFileSync(POOL_PATH, "utf-8"));
  } catch {
    /* overwrite malformed pool */
  }
}

for (const e of extracted) {
  const prev = pool.providers[e.id];
  const unchanged = prev && prev.apiKey === e.apiKey && prev.baseUrl === e.baseUrl;
  pool.providers[e.id] = {
    baseUrl: e.baseUrl,
    apiKey: e.apiKey,
    models: e.models,
    probe: unchanged ? prev.probe : { status: "unprobed" },
  };
}
// Drop entries no longer present in any crush source (stale keys out).
for (const id of Object.keys(pool.providers)) {
  if (!extracted.some((e) => e.id === id)) delete pool.providers[id];
}

writeFileSync(POOL_PATH, JSON.stringify(pool, null, 2) + "\n", { mode: 0o600 });
console.log(`\nPool written: ${POOL_PATH} (gitignored, 0600)`);

// ── Live probe ────────────────────────────────────────────────────────────
if (process.argv.includes("--probe")) {
  const normalize = (u) => {
    const t = u.replace(/\/+$/, "");
    return t.endsWith("/v1") ? t : `${t}/v1`;
  };

  for (const e of extracted) {
    const model = e.models[0];
    const endpoint = `${normalize(e.baseUrl)}/chat/completions`;
    const controller = new AbortController();
    const t = setTimeout(() => controller.abort(), 25000);
    const t0 = Date.now();
    let status, extra = {};
    try {
      const resp = await fetch(endpoint, {
        method: "POST",
        headers: { "content-type": "application/json", authorization: `Bearer ${e.apiKey}` },
        body: JSON.stringify({
          model: model ?? "gpt-4o-mini",
          messages: [{ role: "user", content: "ping" }],
          max_tokens: 1,
        }),
        signal: controller.signal,
      });
      const ms = Date.now() - t0;
      if (resp.ok) {
        const json = await resp.json().catch(() => ({}));
        status = "alive";
        extra = { httpStatus: 200, servedModel: json.model ?? "?", probedAt: new Date().toISOString(), ms };
        console.log(`  ALIVE  ${e.id.padEnd(20)} ${ms}ms served=${String(extra.servedModel).slice(0, 40)}`);
      } else if (resp.status === 400 || resp.status === 404) {
        status = "auth-ok-shape";
        extra = { httpStatus: resp.status, probedAt: new Date().toISOString(), ms };
        console.log(`  SHAPE  ${e.id.padEnd(20)} HTTP ${resp.status} (${ms}ms) — key valid, model id/shape off`);
      } else if (resp.status === 429) {
        status = "auth-ok-rate";
        extra = { httpStatus: 429, probedAt: new Date().toISOString(), ms };
        console.log(`  RATE   ${e.id.padEnd(20)} HTTP 429 (${ms}ms) — key valid, throttled`);
      } else {
        status = "dead";
        extra = { httpStatus: resp.status, probedAt: new Date().toISOString(), ms };
        console.log(`  DEAD   ${e.id.padEnd(20)} HTTP ${resp.status} (${ms}ms)`);
      }
    } catch (err) {
      const ms = Date.now() - t0;
      status = "transport-error";
      extra = { reason: err.name === "AbortError" ? "timeout" : String(err.message ?? err).slice(0, 60), probedAt: new Date().toISOString(), ms };
      console.log(`  DEAD   ${e.id.padEnd(20)} ${extra.reason} (${ms}ms)`);
    } finally {
      clearTimeout(t);
    }
    pool.providers[e.id].probe = { status, ...extra };
  }
  writeFileSync(POOL_PATH, JSON.stringify(pool, null, 2) + "\n", { mode: 0o600 });

  const alive = extracted.filter((e) => pool.providers[e.id].probe.status === "alive");
  const usable = extracted.filter((e) => ["alive", "auth-ok-shape", "auth-ok-rate"].includes(pool.providers[e.id].probe.status));
  console.log(`\nAlive: ${alive.length}/${extracted.length}   usable (alive or auth-ok): ${usable.length}/${extracted.length}`);
  if (alive.length > 0) console.log("Alive ids: " + alive.map((e) => e.id).join(", "));
}
